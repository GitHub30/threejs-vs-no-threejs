-- Cloudflare D1 Schema for AETHER FLOCK Benchmark Telemetry
CREATE TABLE IF NOT EXISTS benchmark_runs (
  id TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  app_version TEXT NOT NULL,
  page_url TEXT,
  user_agent TEXT NOT NULL,
  ua_platform TEXT,
  ua_mobile INTEGER,
  ua_model TEXT,
  ua_arch TEXT,
  ua_bitness TEXT,
  platform TEXT,
  language TEXT,
  cpu_cores INTEGER,
  device_memory_gb REAL,
  max_touch_points INTEGER,
  screen_width INTEGER,
  screen_height INTEGER,
  viewport_width INTEGER,
  viewport_height INTEGER,
  dpr REAL,
  orientation_type TEXT,
  fullscreen INTEGER,
  wasm_simd INTEGER,
  webgpu_supported INTEGER,
  gpu_vendor TEXT,
  gpu_arch TEXT,
  gpu_device TEXT,
  gpu_description TEXT,
  gpu_is_fallback INTEGER,
  webgl_renderer TEXT,
  webgl_vendor TEXT,
  custom_backend TEXT,
  three_backend TEXT,
  custom_init_ms REAL,
  three_init_ms REAL,
  cf_country TEXT,
  cf_colo TEXT,
  device_json TEXT NOT NULL,
  results_json TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS benchmark_scenarios (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  run_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  scenario TEXT NOT NULL,
  entity_count INTEGER NOT NULL,
  custom_fps REAL,
  custom_frame_ms REAL,
  custom_p95_ms REAL,
  custom_p99_ms REAL,
  custom_cpu_ms REAL,
  custom_gpu_ms REAL,
  custom_heap_mb REAL,
  custom_samples INTEGER,
  three_fps REAL,
  three_frame_ms REAL,
  three_p95_ms REAL,
  three_p99_ms REAL,
  three_cpu_ms REAL,
  three_gpu_ms REAL,
  three_heap_mb REAL,
  three_samples INTEGER,
  cpu_speedup REAL,
  fps_ratio REAL,
  FOREIGN KEY (run_id) REFERENCES benchmark_runs(id)
);

CREATE INDEX IF NOT EXISTS idx_runs_created ON benchmark_runs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_scenarios_run ON benchmark_scenarios(run_id);
CREATE INDEX IF NOT EXISTS idx_scenarios_name ON benchmark_scenarios(scenario, created_at DESC);
